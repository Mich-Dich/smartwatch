extern "C" void app_main() {            // ESP‑IDF entry point (must have C linkage)

    ESP_LOGI(APP::TAG, "Starting Audio Spectrum Analyzer");

    lv_display_t *disp = bsp_display_start();
    if (disp) {
        bsp_display_backlight_on();
    }

    bsp_display_lock(-1);
    APP::display::fullscreen_canvas(APP::SA::timer_cb);
    bsp_display_unlock();

    xTaskCreate(APP::SA::audio_fft_task, "audio_fft", 6 * 1024, nullptr, 5, nullptr);
}

